// Copies the website's Banner Studio renderer (the NBBS block inlined in the website's index.html) into the app,
// so banners in the app are drawn by exactly the same code as on minutes.nurbuy.com.
// usage: node scripts/sync-bs-renderer.js <path to website index.html>
const fs = require('fs');
const path = require('path');

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/sync-bs-renderer.js <website index.html>');
  process.exit(1);
}
const html = fs.readFileSync(src, 'utf8');
const begin = html.indexOf('(function(W){', html.indexOf('NBBS:BEGIN'));
const end = html.indexOf('})(window);', begin);
if (begin < 0 || end < 0) {
  console.error('NBBS block not found');
  process.exit(1);
}
const code = html.slice(begin, end + '})(window);'.length);
const out =
  '/* Generated by scripts/sync-bs-renderer.js from the website (shared/bs-render.js). Do not edit by hand. */\n' +
  '/** Banner Studio renderer source, run inside the banner WebView. */\n' +
  'export const NBBS_SOURCE = ' +
  JSON.stringify(code) +
  ';\n';
const target = path.join(__dirname, '..', 'src', 'lib', 'bsRenderer.ts');
fs.writeFileSync(target, out);
console.log('wrote', target, code.length, 'chars');
